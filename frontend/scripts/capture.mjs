import {chromium} from '@playwright/test'
import {mkdir} from 'node:fs/promises'
await mkdir('../docs/screenshots',{recursive:true})
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1})
await page.goto('http://127.0.0.1:5173/')
await page.locator('.stat-card').first().waitFor()
await page.getByTestId('execution-graph').waitFor()
await page.locator('.trace-node').first().waitFor()
await page.screenshot({path:'../docs/screenshots/overview.png',fullPage:true})
await page.goto('http://127.0.0.1:5173/#graph')
await page.getByTestId('execution-graph').waitFor()
await page.locator('.trace-node').filter({hasText:'Validate calculator'}).click()
await page.getByText('Preserved failures',{exact:true}).waitFor()
await page.screenshot({path:'../docs/screenshots/graph-evidence.png',fullPage:true})
await page.setViewportSize({width:390,height:844})
await page.goto('http://127.0.0.1:5173/')
await page.getByTestId('execution-graph').waitFor()
await page.screenshot({path:'../docs/screenshots/mobile.png',fullPage:true})
await browser.close()
console.log('Captured actual running dashboard: overview, graph evidence, mobile.')
